package com.kyant.backdrop.internal

import androidx.compose.ui.graphics.drawscope.DrawScope
import androidx.compose.ui.graphics.layer.GraphicsLayer
import androidx.compose.ui.node.DelegatableNode
import androidx.compose.ui.node.requireDensity
import androidx.compose.ui.unit.IntSize
import androidx.compose.ui.unit.toIntSize

// Upstream uses a context parameter (Kotlin 2.2+); here the draw scope is passed explicitly.
internal fun DelegatableNode.recordLayer(
    scope: DrawScope,
    layer: GraphicsLayer,
    size: IntSize = scope.size.toIntSize(),
    block: DrawScope.() -> Unit
) {
    val density = requireDensity()
    with(scope) { layer.record(size) {
        val prevDensity = drawContext.density
        drawContext.density = density
        try {
            this.block()
        } finally {
            drawContext.density = prevDensity
        }
    } }
}
